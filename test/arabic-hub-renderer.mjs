// Full Classic workspace, isolated plugins, real settings persistence; no live catalog/image requests.
(async () => {
    const { mount, unmount, tick } = await import('/@id/svelte');
    const { default: App } = await import('/src/frontend/classic/App.svelte');
    const { Store: UI } = await import('/src/frontend/classic/stores/Stores.svelte.ts');
    const { Settings } = await import('/src/frontend/classic/stores/Settings.svelte.ts');
    const { MangaScraper } = await import('/src/engine/providers/MangaPlugin.ts');
    const { Tags } = await import('/src/engine/Tags.ts');
    const { Store } = await import('/src/engine/StorageController.ts');
    const { ArabicFirstKey } = await import('/src/frontend/classic/models/PluginPresentation.ts');
    const { HakuNeko: engine } = globalThis;
    const storage = engine.SettingsManager.storage;
    let fetched = 0;
    class Local extends MangaScraper {
        async Initialize() {}
        async FetchMangas() { fetched++; return []; }
    }
    const ar = new Local('hub-ar', 'Z English Name', 'https://arabic.invalid', Tags.Language.Arabic).CreatePlugin(storage, engine.SettingsManager);
    const en = new Local('hub-en', 'A اسم عربي', 'https://english.invalid', Tags.Language.English).CreatePlugin(storage, engine.SettingsManager);
    const multi = new Local('hub-multi', 'B Multilingual', 'https://multi.invalid', Tags.Language.Multilingual).CreatePlugin(storage, engine.SettingsManager);
    const both = new Local('hub-both', 'C Both', 'https://both.invalid', Tags.Language.Arabic, Tags.Language.Multilingual).CreatePlugin(storage, engine.SettingsManager);
    const bookmarks = new Local('hub-bookmarks', 'Bookmarks', 'https://bookmarks.invalid').CreatePlugin(storage, engine.SettingsManager);
    bookmarks.GetEntriesWithUnflaggedContent = async () => [];
    engine.BookmarkPlugin = bookmarks;
    engine.PluginController.WebsitePlugins = [en, multi, ar, both];
    Settings.StartupGuideEnabled.Value = false;
    Settings.ContentPanel.Value = false;
    Settings.ArabicFirstPlugins.Value = true;
    UI.selectedPlugin = undefined; UI.selectedMedia = undefined; UI.selectedItem = undefined;
    UI.contentscreen = '/isolated-hub-test'; UI.page = 'media';
    const checks = [];
    const record = (name, passed) => { if (!passed) throw new Error(name); checks.push({ name, passed }); console.log(name, passed); };
    const wait = async predicate => { const end = Date.now() + 12000; while (!await predicate()) { if (Date.now() > end) throw new Error(`Hub wait failed: ${document.body.innerText.slice(-1200)}`); await new Promise(resolve => setTimeout(resolve, 40)); } };
    const click = async text => { const action = [...document.querySelectorAll('button,a')].find(el => el.checkVisibility() && el.textContent.trim() === text); if (!action) throw new Error('Missing hub action: ' + text); action.click(); await tick(); };
    const input = async (element, value) => { element.value = value; element.dispatchEvent(new Event('input', { bubbles: true })); await tick(); };
    const target = document.createElement('div'); document.body.append(target);
    let app = mount(App, { target });
    await wait(() => document.querySelector('#Media input[type="search"]'));
    const media = document.querySelector('#Media');
    const filter = document.querySelector('#Media input[type="search"]');
    await input(filter, 'original-filter');
    const sidebar = [...document.querySelectorAll('a')].find(el => el.textContent.trim() === 'Arabic Manga');
    const links = [...document.querySelectorAll('a')];
    record('Arabic Manga is a real Classic sidebar destination beside Archive Site', !!sidebar && links.indexOf(sidebar) === links.findIndex(link => link.textContent.trim() === 'Archive Site') + 1);
    sidebar.click(); await tick();
    await wait(() => document.querySelector('[data-testid="arabic-manga-hub"]')?.checkVisibility());
    record('Hub opens as a full page without a selected plugin even when the content panel is disabled', UI.selectedPlugin === undefined && !media.checkVisibility() && document.querySelector('#ArabicManga').clientWidth > 800);
    record('Search is the default hub page and only three main sections are shown', !!document.querySelector('[data-testid="shared-search"]') && document.querySelector('#ArabicManga nav').textContent.replace(/\s+/g,' ').trim() === 'Search Sites Downloads');
    await click('Sites');
    const ids = () => [...document.querySelectorAll('[data-testid="arabic-site"]')].map(el => el.dataset.siteId);
    record('Arabic tags show English-named Arabic sites and exclude Arabic-named English and multilingual-only sites', ids().join(',') === 'hub-both,hub-ar');
    record('Unknown health is explicit and future sections have no fake action buttons', document.querySelector('#ArabicManga').textContent.includes('No live health check') && document.querySelector('#ArabicManga nav').querySelectorAll('button').length === 3 && document.querySelector('#ArabicManga nav').querySelectorAll('a').length === 0);
    const search = document.querySelector('[data-testid="arabic-site-filter"]');
    await input(search, 'arabic.invalid');
    record('Hub filters sites by host', ids().join(',') === 'hub-ar');
    await input(search, 'missing');
    record('Hub presents an empty filter result without fetching', ids().length === 0 && document.querySelector('#ArabicManga').textContent.includes('No matching sites'));
    await input(search, '');
    const scope = document.querySelector('[data-testid="arabic-site-scope"]'); scope.value = 'multilingual-unconfirmed'; scope.dispatchEvent(new Event('change', { bubbles: true })); await tick();
    record('Multilingual-only candidates are separately labeled as unconfirmed Arabic', ids().join(',') === 'hub-multi' && document.querySelector('[data-testid="arabic-site"]').textContent.includes('Arabic unconfirmed'));
    await click('Back to Media List');
    record('Returning preserves the mounted Media List and its original search text', document.querySelector('#Media') === media && media.checkVisibility() && filter.value === 'original-filter');
    await input(filter, '');
    // Inspect the actual Carbon combo list and change its persisted ordering preference.
    document.querySelector('#PluginSelect').click(); await tick();
    await wait(() => document.querySelectorAll('#PluginSelect-item-0, [role="option"]').length > 0);
    const options = () => [...document.querySelectorAll('[role="option"]')].map(el => el.textContent.trim());
    record('Select a Plugin lists Arabic-tagged sites before other languages by default', options().findIndex(text => text.includes('Z English Name')) < options().findIndex(text => text.includes('A اسم عربي')));
    const preference = document.querySelector('#Media [data-testid="arabic-first-preference"]');
    const orderRect = document.querySelector('#PluginOrder').getBoundingClientRect();
    record('The ordering control occupies its own full-width Media List row', orderRect.width > 250 && orderRect.bottom <= document.querySelector('#Plugin').getBoundingClientRect().top);
    preference.click(); await tick();
    document.querySelector('#PluginSelect').click(); await tick();
    if (!document.querySelector('[role="option"]')) { document.querySelector('#PluginSelect').click(); await tick(); }
    record('Disabling Arabic priority restores alphabetical ordering in the actual plugin selector', options().findIndex(text => text.includes('A اسم عربي')) < options().findIndex(text => text.includes('Z English Name')));
    const englishOption = [...document.querySelectorAll('[role="option"]')].find(el => el.textContent.includes('A اسم عربي'));
    englishOption.click(); await tick();
    record('Non-Arabic plugins remain selectable through the original combo box', UI.selectedPlugin === en);
    document.querySelector('#PluginSelect').click(); await tick();
    const bookmarkOption = [...document.querySelectorAll('[role="option"]')].find(el => el.textContent.includes('Bookmarks'));
    bookmarkOption.click(); await tick();
    record('The original bookmarks entry remains selectable and unchanged', UI.selectedPlugin === bookmarks && engine.BookmarkPlugin === bookmarks);
    await wait(async () => (await storage.LoadPersistent(Store.Settings, 'frontend.classic'))?.[ArabicFirstKey] === false);
    record('Ordering preference commits to isolated IndexedDB', Settings.ArabicFirstPlugins.Value === false);
    sidebar.click(); await tick(); await click('Sites');
    await wait(() => document.querySelector('[data-site-id="hub-ar"]'));
    [...document.querySelectorAll('[data-site-id="hub-ar"] button')].find(button => button.textContent.trim() === 'Open Site').click(); await tick();
    record('Opening a hub site selects the original plugin and returns to Media List', UI.selectedPlugin === ar && UI.page === 'media' && media.checkVisibility());
    record('Hub navigation and selection never fetched a catalog or queued a download', fetched === 0 && engine.DownloadManager.Queue.Value.length === 0);
    UI.page = 'arabic-manga'; await tick();
    const hub = document.querySelector('#ArabicManga');
    record('The hub is independent of the current plugin after reopening', !!hub && ids().join(',') === 'hub-both,hub-ar');
    Settings.ContentPanel.Value = true; await tick();
    record('Hub remains a full page when the content panel is enabled', !document.querySelector('#Content').checkVisibility() && hub.checkVisibility());
    await ipcRenderer.invoke('ArchiveHubTest::Capture');
    await unmount(app); target.replaceChildren();
    const extras = Array.from({ length: 30 }, (_, i) => new Local(`hub-extra-${i}`, `Extra ${i}`, 'https://extra.invalid', Tags.Language.Arabic).CreatePlugin(storage, engine.SettingsManager));
    engine.PluginController.WebsitePlugins = [ar, both, en, multi, ...extras];
    app = mount(App, { target });
    await wait(() => document.querySelectorAll('[data-testid="arabic-site"]').length === 20);
    const firstPage = ids();
    await tick();
    record('Remounting the workspace does not redirect an existing hub to Media List', UI.page === 'arabic-manga');
    await click('Next');
    record('Hub paginates more than twenty Arabic sources without hiding the remaining sources', ids().length === 12 && new Set([...firstPage, ...ids()]).size === 32);
    await input(document.querySelector('[data-testid="arabic-site-filter"]'), 'hub-extra-29');
    record('Filtering from a later page resets pagination and reveals its match', ids().join(',') === 'hub-extra-29');
    await unmount(app); target.remove();
    UI.page = 'media'; UI.selectedPlugin = undefined;
    return checks;
})()
